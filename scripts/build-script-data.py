"""Build dist/script-data.js (SCRIPT_DATA) for the Thai script course from scripts/script-course/script-data.json.

script-data.json is generated by scripts/script-course/gen_script_data.py and verified by
check_script_data.py (lesson order, coverage of all 44 consonants, tone/ro recomputed from the rules).
Lesson ids (s01…) key learners' progress in localStorage (thai-steps-script-v1): do not renumber them.
"""
import json,pathlib
P=pathlib.Path(__file__).resolve().parents[1]
d=json.loads((P/'scripts/script-course/script-data.json').read_text())
assert len(d['consonants'])==44 and len({l['id'] for l in d['lessons']})==len(d['lessons'])
(P/'dist/script-data.js').write_text('// Thai script course (AI-authored, AI-reviewed). Built by scripts/build-script-data.py.\nconst SCRIPT_DATA='+json.dumps(d,ensure_ascii=False,separators=(',',':'))+';\n')
print(len(d['lessons']),'lessons')
