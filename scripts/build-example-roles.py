#!/usr/bin/env python3
"""Build dist/example-roles.js from scripts/example-roles/roles.json.

roles.json maps "<lesson id>-<example index>" to one role code per word of that
example (the words are the ones segmentExample() in dist/vocabulary.js returns).
The codes are the keys of roleInfo in dist/structures.js, so the examples under
「会話で使ってみる」 use the same colours as the 文の組み立て panel.
AI-assigned and AI-checked; not verified by a native speaker.
tests/example-roles.test.cjs checks every array against the real segmentation.
"""
import json, pathlib, re, sys
root = pathlib.Path(__file__).resolve().parent.parent
roles = json.loads((root / 'scripts/example-roles/roles.json').read_text(encoding='utf-8'))
codes = set(re.findall(r"(\w+):\['", (root / 'dist/structures.js').read_text(encoding='utf-8').split('\n')[0]))
bad = [(k, c) for k, v in roles.items() for c in v if c not in codes]
if bad:
    sys.exit(f'unknown role codes: {bad[:10]}')
out = '// Generated by scripts/build-example-roles.py. Do not edit.\nconst EXAMPLE_ROLES=' + json.dumps(roles, ensure_ascii=False, separators=(',', ':')) + ';\n'
(root / 'dist/example-roles.js').write_text(out, encoding='utf-8')
print(f'{len(roles)} examples, {sum(len(v) for v in roles.values())} words')
