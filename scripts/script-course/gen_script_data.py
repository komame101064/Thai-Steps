    d = {"id": id, "stage": stage, "stageTitle": S[stage], "title": title, "intro": intro,
         "newConsonants": list(nc), "newVowels": list(nv), "newMarks": list(nm)}
    d.update(extra)
    d["points"] = points
    d["readings"] = readings
    if tq:
        d["toneQuestions"] = list(tq)
    L.append(d)


