#!/usr/bin/env python3
"""Build dist/word-usage.js from scripts/word-usage/part-NN.json (see scripts/word-usage/SPEC.md).

WORD_USAGE = {g: {gid: {w: [ids], lead, use: {id: text}, tip, ex: [{th, ro, ja}]}}, by: {id: [gid, ...]}}
Only groups with status ok and at least two words that exist in the bank are published.
AI-written usage notes, not checked by a native speaker.
"""
import json, pathlib
R = pathlib.Path(__file__).resolve().parent.parent
bank = {}
for f in ['word-bank.json', 'word-bank-more.json']:
    for w in json.loads((R / 'dist' / f).read_text()):
        bank[w['id']] = w
g, by = {}, {}
for f in sorted((R / 'scripts/word-usage').glob('part-*.json')):
    for x in json.loads(f.read_text()):
        if x.get('status') != 'ok':
            continue
        ids = [i for i in dict.fromkeys(x.get('keep', []) + x.get('add', [])) if i in bank]
        if len(ids) < 2:
            continue
        use = {i['id']: i['use'] for i in x.get('items', []) if i.get('id') in ids}
        g[x['gid']] = {'w': ids, 'lead': x['lead'], 'use': use, **({'tip': x['tip']} if x.get('tip') else {}),
                       **({'ex': x['examples'][:2]} if x.get('examples') else {})}
        for i in ids:
            by.setdefault(i, []).append(x['gid'])
out = '// Generated by scripts/build-word-usage.py. Do not edit.\nconst WORD_USAGE=' + json.dumps({'g': g, 'by': by}, ensure_ascii=False, separators=(',', ':')) + ';\n'
(R / 'dist/word-usage.js').write_text(out, encoding='utf-8')
print(f'{len(g)} groups, {len(by)} words')
