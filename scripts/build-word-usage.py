#!/usr/bin/env python3
"""Build dist/word-usage.js from scripts/word-usage/part-NN.json (see scripts/word-usage/SPEC.md).

WORD_USAGE = {g: {gid: {w: [ids], lead, use: {id: text}, tip, ex: [{th, ro, ja}]}}, by: {id: [gid, ...]}}
Only groups with status ok and at least two words that exist in the bank are published.
AI-written usage notes, not checked by a native speaker.
"""
import json, pathlib
R = pathlib.Path(__file__).resolve().parent.parent
bank = {}
for f in ['word-bank.json', 'word-bank-more.json']:
    for w in json.loads((R / 'dist' / f).read_text()):
        bank[w['id']] = w
# Entries hidden in the app (WORD_DROP and the phrase lists it spreads in) are not compared.
import re
app = (R / 'dist/words-app.js').read_text()
hidden = set()
for name in ('WORD_DROP', 'PHRASE_PADDED', 'PHRASE_ENDING'):
    m = re.search(r'const ' + name + r'=new Set\(\[(.*?)\]\)', app, re.S)
    if m: hidden |= set(re.findall(r'tl-\d+', m.group(1)))
bank = {k: v for k, v in bank.items() if k not in hidden and not v.get('generalHidden')}
pairs = {}
for f in sorted((R / 'scripts/word-usage').glob('pairs-*.json')):
    pairs.update(json.loads(f.read_text()))
g, by = {}, {}
for f in sorted((R / 'scripts/word-usage').glob('part-*.json')):
    for x in json.loads(f.read_text()):
        if x.get('status') != 'ok':
            continue
        ids = [i for i in dict.fromkeys(x.get('keep', []) + x.get('add', [])) if i in bank]
        if len(ids) < 2:
            continue
        use = {i['id']: i['use'] for i in x.get('items', []) if i.get('id') in ids}
        g[x['gid']] = {'w': ids, 'lead': x['lead'], 'use': use, **({'tip': x['tip']} if x.get('tip') else {}),
                       **({'ex': x['examples'][:2]} if x.get('examples') else {}),
                       **({'pr': [p for p in pairs[x['gid']] if p.get('id') in ids][:3]} if len([p for p in pairs.get(x['gid'], []) if p.get('id') in ids]) >= 2 else {})}
        for i in ids:
            by.setdefault(i, []).append(x['gid'])
# Near-duplicate groups (the same words compared in several places, e.g. แค่／เท่านั้น／เพียง／เฉยๆ) are merged:
# the larger group is kept and a group sharing at least 75% of the smaller one's words (and 2+ words) is dropped.
order = sorted(g, key=lambda k: (-len(g[k]['w']), k)); kept = []; dropped = []
for k in order:
    ws = set(g[k]['w'])
    if any(len(ws & set(g[j]['w'])) >= max(2, 0.75 * min(len(ws), len(g[j]['w']))) for j in kept):
        dropped.append(k); continue
    kept.append(k)
g = {k: g[k] for k in sorted(kept)}
by = {}
for k, x in g.items():
    for i in x['w']:
        by.setdefault(i, []).append(k)
print(f'merged {len(dropped)} near-duplicate groups')
out = '// Generated by scripts/build-word-usage.py. Do not edit.\nconst WORD_USAGE=' + json.dumps({'g': g, 'by': by}, ensure_ascii=False, separators=(',', ':')) + ';\n'
(R / 'dist/word-usage.js').write_text(out, encoding='utf-8')
print(f'{len(g)} groups, {len(by)} words')
